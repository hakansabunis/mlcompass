def _importable(name: str) -> bool:
    """Can `SCRIPT_INTERPRETER` import this name, right now?

    `find_spec` rather than an import: the answer is wanted, the side effects
    are not. This runs in the same interpreter that executes the emitted script
    — `SCRIPT_INTERPRETER` is `sys.executable` — so it is reading the
    environment the prompt is about rather than one like it.
    """
    try:
        return importlib.util.find_spec(name) is not None
    except (ImportError, ValueError):
        # A package whose parent is missing, or a name that is not a valid
        # module path. Either way it is not importable, which is the question.
        return False


@functools.cache
def _packages_distributions() -> dict[str, list[str]]:
    """Import name -> distribution names, read once.

    Cached because it is not cheap: it walks every distribution on `sys.path`
    and takes over two seconds in this environment, and the roster asks about
    it once per importable name. The environment does not change under a
    running battery, so reading it once is not a shortcut — it is the same
    answer, arrived at without spending half a minute per prompt.
    """
    try:
        return dict(importlib.metadata.packages_distributions())
    except Exception:  # pragma: no cover - metadata backends vary
        return {}


def _distribution_version(name: str) -> str:
    """The installed version behind an import name, or "" if it cannot be told."""
    distributions = _packages_distributions().get(name, [])
    for distribution in distributions:
        with contextlib.suppress(importlib.metadata.PackageNotFoundError):
            return f"{distribution} {importlib.metadata.version(distribution)}"
    return ""


def environment_packages(roster: tuple[str, ...] = PACKAGE_ROSTER) -> str:
    """Render §2's package list from the environment, for every arm alike.

    One line per roster entry that this interpreter can import, in roster
    order, carrying the distribution and version where they can be resolved —
    `sklearn (scikit-learn 1.9.1)` rather than a bare name, because a model
    choosing an API cares which major version it is writing against.

    Nothing here is a literal. The roster decides what is asked; `find_spec`
    decides what is answered.
    """
    lines = []
    for name in roster:
        if name in EXCLUDED_FROM_ROSTER:
            raise RuntimeError(
                f"{name!r} is on the package roster. The control arm is defined by "
                "not being given mlcompass, and a package list naming it would tell "
                "that arm the tool exists — a difference between the arms that "
                "ab_protocol.md §2 does not allow, introduced by the harness."
            )
        if not _importable(name):
            continue
        # `numpy 2.4.6` where the import name is the distribution name, and
        # `sklearn (scikit-learn 1.9.1)` where it is not — the second is worth
        # the parentheses and the first is not worth `numpy (numpy 2.4.6)`.
        distribution = _distribution_version(name)
        if not distribution:
            lines.append(f"  - {name}")
        elif distribution.startswith(f"{name} "):
            lines.append(f"  - {distribution}")
        else:
            lines.append(f"  - {name} ({distribution})")
    if not lines:
        raise RuntimeError(
            "no importable package on the roster, so the prompt would promise a "
            "list and show an empty one. That reads as 'nothing is installed', "
            "which no arm could write a training script against. Refusing to "
            f"build a prompt from it (roster of {len(roster)} checked with "
            f"{SCRIPT_INTERPRETER})."
        )
    return "\n".join(lines)


