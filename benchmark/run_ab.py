def append_result(row: dict[str, Any]) -> None:
    """Append one run to `ab_results.csv`, refusing a file of a different shape.

    `csv.DictWriter` writes values in *its* field order and never looks at the
    header already on disk. Appending a 1.1 row to the 1.0 file would therefore
    line a temperature up under an arm column and say nothing about it; the
    corruption would surface much later, in a reader wondering why an arm was
    called `1.0`. A/B 1.1 added four columns, so this is not hypothetical — the
    1.0 rows live in `ab_results_v1.0.csv` and this file starts fresh.

    The 1.1 rows were moved out for a different reason, and the file name says
    which: `ab_results_v1.1_superseded.csv`. Their columns match this schema
    exactly, so nothing would have stopped them being appended to; what is
    wrong with them is §9 A4 — they were scored on a holdout sharing 71 of its
    187 rows with train. Mixing them in beside 1.2 rows would have put results
    and non-results in one column of one file, distinguishable only by reading
    `protocol_version` and knowing what A4 was.

    The three 1.2 rows moved to `ab_results_v1.2_validation.csv` for a third
    reason, and it is the weakest of the three: nothing is wrong with them.
    They are pipeline validation, not results — one of them is the `advise`
    arm dying on `import imblearn` that §9 A5 was written from — and the file
    they were in is about to hold a scored battery. The name says validation
    rather than superseded because the A4 split under them is the current one.
    """
    existing = AB_RESULTS.read_text(encoding="utf-8").strip() if AB_RESULTS.exists() else ""
    if existing:
        header = next(csv.reader([existing.splitlines()[0]]))
        if header != RESULT_COLUMNS:
            missing = [c for c in RESULT_COLUMNS if c not in header]
            extra = [c for c in header if c not in RESULT_COLUMNS]
            raise ResultSchemaMismatch(
                f"{AB_RESULTS.name} was written under a different set of columns "
                f"({len(header)} there, {len(RESULT_COLUMNS)} here). "
                f"Missing: {missing or 'none'}. Unexpected: {extra or 'none'}. "
                "Appending would silently shift every value into the wrong column. "
                "Move the old file aside (e.g. to ab_results_v1.0.csv) and run again; "
                "rows are evidence and are not rewritten in place."
            )
    with AB_RESULTS.open("a", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=RESULT_COLUMNS)
        if not existing:
            writer.writeheader()
        writer.writerow({k: row.get(k, "") for k in RESULT_COLUMNS})


class PlanViolation(RuntimeError):
    """What is about to run is not what the frozen plan says will run."""


def read_plan_cells(plan_path: Path) -> dict[str, Any]:
    """Parse the frozen plan's cell table back into what it commits to.

    The plan's `## Cells` table IS the pre-registration: it names every
    (dataset, arm, model) cell, the repetitions and the seeds. Parsing it back
    is what turns it from a document into a constraint.

    This exists because for one run it was not a constraint. `--experiment-id`
    checked only that `plan.md` EXISTED, then ran whatever the command line
    said. A plan froze 12 `control+revise` cells at 3 repetitions -- 36 runs --
    and the execution did 48 across all four arms at 1 repetition, appended
    them under the plan's own id, and reported success. The harness's own
    suggested command line was the cause: it printed `--experiment-id` and
    `--panel-id` and dropped `--arm` and `--repeats`, so following the
    instruction guaranteed the mismatch.

    A pre-registration nobody checks is a paragraph, not a method.
    """
    rows: list[tuple[str, str, str]] = []
    repeats: set[int] = set()
    seeds: set[tuple[int, ...]] = set()
    in_table = False
    for line in plan_path.read_text(encoding="utf-8").splitlines():
        if line.startswith("| dataset | arm | model |"):
            in_table = True
            continue
        if in_table:
            if not line.startswith("|"):
                break
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) < 5 or set(cells[0]) <= set("- "):
                continue
            rows.append((cells[0], cells[1], cells[2]))
            try:
                repeats.add(int(cells[3]))
                seeds.add(tuple(int(s) for s in cells[4].split(",")))
            except ValueError:
                continue
    if not rows:
        raise PlanViolation(
            f"{plan_path} has no readable cell table, so it cannot be enforced. "
            "Re-freeze the plan with --plan."
        )
    return {
        "cells": sorted(set(rows)),
        "datasets": sorted({d for d, _, _ in rows}),
        "arms": sorted({a for _, a, _ in rows}),
        "panel_ids": sorted({m for _, _, m in rows}),
        "repeats": sorted(repeats),
        "seeds": sorted(seeds),
    }


def enforce_plan(
    plan_path: Path,
    *,
    datasets: list[dict[str, Any]],
    arms: tuple[str, ...],
    panel_ids: list[str],
    repeats: int,
    seeds: list[int],
) -> None:
    """Abort unless the run about to start is the one the plan froze."""
    plan = read_plan_cells(plan_path)
    about_to_run: dict[str, Any] = {
        "datasets": sorted({d["dataset_id"] for d in datasets}),
        "arms": sorted(arms),
        "panel_ids": sorted(panel_ids),
        "repeats": [repeats],
        "seeds": [tuple(seeds[:repeats])],
    }
    differences = []
    for field in ("datasets", "arms", "panel_ids", "repeats", "seeds"):
        if about_to_run[field] != plan[field]:
            differences.append(
                f"  {field}:"
                + "\n"
                + f"    plan says  {plan[field]}"
                + "\n"
                + f"    run would  {about_to_run[field]}"
            )
    if differences:
        raise PlanViolation(
            f"the run does not match the frozen plan at {plan_path}."
            + "\n"
            + "\n".join(differences)
            + "\n"
            + "\n"
            + "The plan is the pre-registration. Either pass the flags that "
            "reproduce it, or freeze a new plan with --plan for the run you "
            "actually want. Nothing was executed and nothing was written."
        )


def write_plan(
    experiment_id: str,
    gt: dict[str, Any],
    datasets: list[dict[str, Any]],
    panel_ids: list[str],
    arms: list[str],
    repeats: int,
    seeds: list[int],
    timeouts: tuple[int, int, int],
) -> Path:
    plan_dir = RUNS / experiment_id
    plan_dir.mkdir(parents=True, exist_ok=True)
    plan = plan_dir / "plan.md"
    llm_timeout, script_timeout, score_timeout = timeouts
    cells = [
        f"| {d['dataset_id']} | {a} | {p} | {repeats} | {', '.join(map(str, seeds))}"
        f" | {METRIC_BY_TASK.get(d['task'], '(no metric fixed)')} |"
        for d in datasets
        for a in arms
        for p in panel_ids
    ]
    plan.write_text(
        "\n".join(
            [
                f"# A/B experiment plan — {experiment_id}",
                "",
                f"Frozen at {_utc_now()} (UTC), before execution.",
                "",
                f"- Protocol: ab_protocol.md, version {AB_PROTOCOL_VERSION}",
                f"- Dataset registry: ground_truth.json v{gt['registry_version']},"
                f" frozen {gt['frozen_at_utc']} (used here for the pinned files,"
                " their targets and their task types only — the case list is not"
                " scored by this battery)",
                f"- mlcompass commit: {_git('rev-parse', 'HEAD')}",
                f"- Tree dirty at planning time: {bool(_git('status', '--porcelain'))}",
                f"- Python {platform.python_version()} on {platform.platform()}",
                f"- Repetitions per cell: {repeats}; seeds {seeds}",
                f"- Timeouts: model call {llm_timeout}s, emitted script {script_timeout}s,"
                f" holdout scoring {score_timeout}s",
                f"- Max completion tokens: {MAX_COMPLETION_TOKENS}",
                "",
                "## Generation settings (section 5, frozen by §9 A3)",
                "",
                f"- Temperature: {TEMPERATURE} on every arm and every provider, sent explicitly",
                "  in the request body rather than left to the provider default, and recorded in",
                "  every run record.",
                "- A provider that rejects the parameter by name has the rejection recorded and",
                "  its `temperature_used` reads `unknown`. The row is kept; it never claims a",
                "  temperature the provider did not honour. A failure that does not name the",
                "  parameter is recorded as a failure, not read as a rejection.",
                "",
                "## Split (section 3, frozen by §9 A2 and A4)",
                "",
                f"- Holdout fraction: {HOLDOUT_FRACTION}",
                f"- Stratified on the target for classification tasks: {STRATIFY_CLASSIFICATION}",
                f"- Split on duplicate groups: {GROUP_ON_DUPLICATES}",
                "- Split once per (dataset, seed) with `sklearn.model_selection.train_test_split`,",
                "  `shuffle=True`, `random_state=<seed>`, drawing *groups of identical rows*",
                "  rather than rows, and stratifying on each group's target. Every arm and every",
                "  repetition at that seed are scored on the identical holdout.",
                "- The grouping removes the leak without removing the defect: no holdout row",
                "  appears verbatim in train, and duplicates remain inside train.csv, so",
                "  `leak_duplicate_rows` is still something an emitted script can commit. Each",
                "  run record carries the measured contamination count next to the train",
                "  duplicate count, because those are the two halves of §9 A4.",
                "- All three values are the protocol's, read back out of ab_protocol.md §3 by",
                "  `verify_protocol_constants` before any cell runs. A harness that disagreed",
                "  with the document would abort rather than split.",
                "",
                "## Execution environment (section 2, frozen by §9 A5)",
                "",
                f"- Interpreter: `{SCRIPT_INTERPRETER}`, Python {platform.python_version()}.",
                "  The same one that executes every emitted script, so the prompt describes",
                "  the environment the script actually meets rather than one like it.",
                "- Every arm's prompt carries the list below, identically. It is generated by",
                f"  asking that interpreter which of a frozen roster of {len(PACKAGE_ROSTER)}",
                "  ML-relevant names it can import, at the moment the prompt is built — not",
                "  written by hand, which would drift from the environment the first time",
                "  anything was installed or removed.",
                "- **Curated, not complete.** `pip list` here holds 171 distributions and one",
                "  of them is `mlcompass`; dumping it would print the intervention's own name",
                "  in the control arm's prompt, and §2 does not allow the control arm to be",
                "  told the tool exists. The prompt therefore says an import of anything not",
                "  listed *may* fail, rather than claiming a completeness it does not have.",
                "- Why it is stated at all (§9 A5): a validation run's `advise` arm died on",
                "  `import imblearn`, so `runs_at_all` was partly measuring this machine's",
                "  `pip list`. The confound is directional — advise output recommends handling",
                "  class imbalance, which points at the resampling libraries most likely to be",
                "  absent — so leaving it unstated penalises the treatment arms for taking the",
                "  intervention's advice.",
                "",
                "```",
                environment_packages(),
                "```",
                "",
                "## Arms (section 2, three since §9 A1)",
                "",
                "- `control`: train.csv path, target column, column listing, the package list",
                "  above, write-a-script task.",
                "- `advise`: byte-identical prompt plus an appended block carrying the verbatim",
                "  stdout of `mlcompass advise` on the same train.csv. The advise prompt is",
                "  constructed as `control + block`, so those two arms cannot differ elsewhere.",
                "- `advise+audit`: the `advise` arm's turn, byte for byte, then one revision",
                "  round. `mlcompass audit` is run on the script *that arm's own* first turn",
                "  produced, its verbatim stdout goes back to the same model in a second user",
                "  message, and the revised script is the one scored. No arm ever sees another",
                "  arm's output. An audit that finds nothing still produces the round, with an",
                "  empty findings block.",
                "",
                "## Models (section 5 — reported per model, never pooled)",
                "",
                *[
                    f"- `{p}`: `{PANEL[p]['model']}` via `{PANEL[p]['provider']}` at "
                    f"{PANEL[p]['base_url'] or 'the provider default endpoint'}"
                    f" — {PANEL[p]['note']}."
                    for p in panel_ids
                ],
                "",
                "## Cells",
                "",
                "| dataset | arm | model | repeats | seeds | metric |",
                "| --- | --- | --- | --- | --- | --- |",
                *cells,
                "",
                "## Scoring (sections 3 and 4)",
                "",
                "- `holdout_score`: the saved model loaded by the harness and predicted on",
                "  holdout.csv. ROC AUC for binary, macro F1 for multiclass, R² for regression.",
                "  A script that saved nothing loadable scores blank with a recorded reason;",
                "  no number is substituted.",
                "- `process_defects`: the six-item checklist, a frozen deterministic function of",
                "  the emitted source. Never scored by a model.",
                "- `runs_at_all`: the emitted script's exit status.",
                "",
                "## Execution order",
                "",
                "Sequential, dataset-major then arm then model. Every run executes the emitted",
                "script as a subprocess in a fresh temp workspace holding train.csv only, under",
                "a wall-clock timeout, with holdout.csv outside that workspace.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    return plan


def main() -> int:
    ap = argparse.ArgumentParser(description="Run the ab_protocol.md with/without battery.")
    ap.add_argument("--experiment-id", default=None, help="reuse an existing frozen plan")
    ap.add_argument("--dataset", action="append", help="dataset_id to run, repeatable; default all")
    ap.add_argument(
        "--panel-id",
        action="append",
        help=f"model lane, repeatable. Panel: {', '.join(sorted(PANEL))}",
    )
    ap.add_argument("--arm", action="append", choices=list(ARMS), help="default: both arms")
    ap.add_argument("--repeats", type=int, default=1)
    ap.add_argument("--seed", type=int, action="append", help="seed per repetition (repeatable)")
    ap.add_argument("--timeout", type=int, default=DEFAULT_LLM_TIMEOUT, help="model call timeout")
    ap.add_argument("--script-timeout", type=int, default=DEFAULT_SCRIPT_TIMEOUT)
    ap.add_argument("--score-timeout", type=int, default=DEFAULT_SCORE_TIMEOUT)
    ap.add_argument("--audit-timeout", type=int, default=DEFAULT_AUDIT_TIMEOUT)
    ap.add_argument("--plan", action="store_true", help="freeze a plan and exit without running")
    ap.add_argument("--dry-run", action="store_true", help="print the cells and exit")
    args = ap.parse_args()

    # §9 A2, A3 and A4 made the split geometry and the temperature the
    # protocol's values. Before anything is planned or run, check that this
    # harness still agrees with the document; a battery scored under settings
    # the protocol does not describe is evidence for nothing.
    try:
        frozen = verify_protocol_constants()
    except ProtocolDrift as exc:
        print(f"Protocol drift, refusing to run:\n  {exc}")
        return 1
    print(
        f"Protocol constants confirmed against {Path(frozen['source']).name}: "
        f"holdout {frozen['holdout_fraction']}, "
        f"stratified {frozen['stratify_classification']}, "
        f"grouped on duplicates {frozen['group_on_duplicates']}, "
        f"temperature {frozen['temperature']}, "
        f"package list in the prompt {frozen['state_package_list']}."
    )
    # §9 A5. Printed rather than assumed, because the number is a fact about
    # this machine at this moment and the run is about to put it in 108 prompts.
    stated = environment_packages()
    print(
        f"Execution environment stated to every arm: {len(stated.splitlines())} of "
        f"{len(PACKAGE_ROSTER)} rostered packages importable by "
        f"{Path(SCRIPT_INTERPRETER).name} (Python {platform.python_version()}), "
        f"digest {hashlib.sha256(stated.encode('utf-8')).hexdigest()[:12]}."
    )

    gt = _load_ground_truth()
    datasets = gt["datasets"]
    if args.dataset:
        wanted = set(args.dataset)
        datasets = [d for d in datasets if d["dataset_id"] in wanted]
        missing = wanted - {d["dataset_id"] for d in datasets}
        if missing:
            print(f"Unknown dataset_id(s): {sorted(missing)}")
            return 1

    panel_ids = list(args.panel_id or [])
    unknown = [p for p in panel_ids if p not in PANEL]
    if unknown:
        print(f"Unknown panel id(s): {unknown}; known: {sorted(PANEL)}")
        return 1
    if not panel_ids:
        print("Every A/B cell needs a model. Pass --panel-id at least once.")
        print(f"Panel: {', '.join(sorted(PANEL))}")
        return 1

    arms = list(args.arm or ARMS)
    seeds = args.seed or list(range(args.repeats))
    if len(seeds) < args.repeats:
        seeds = (seeds * args.repeats)[: args.repeats]

    problems = _verify_inputs(gt)
    if problems:
        print("Input verification failed (protocol.md section 2):")
        for problem in problems:
            print(f"  {problem}")
        print("\nRun: python benchmark/fetch_datasets.py --verify")
        return 1
    print(f"Inputs verified: {len(gt['datasets'])} dataset(s) match the registry.\n")

    for dataset in datasets:
        if dataset["task"] not in METRIC_BY_TASK:
            print(f"{dataset['dataset_id']}: no metric is fixed for task {dataset['task']!r}.")
            return 1

    # The plan check runs BEFORE the dry-run listing, not after it. A
    # violation you can only discover by spending money is not a check.
    if args.experiment_id:
        _planned = RUNS / args.experiment_id / "plan.md"
        if _planned.exists():
            try:
                enforce_plan(
                    _planned,
                    datasets=datasets,
                    arms=arms,
                    panel_ids=panel_ids,
                    repeats=args.repeats,
                    seeds=seeds,
                )
            except PlanViolation as exc:
                print(f"\nPLAN VIOLATION: {exc}", file=sys.stderr)
                return 1

    if args.dry_run:
        for dataset in datasets:
            for arm in arms:
                for panel_id in panel_ids:
                    print(
                        f"  {dataset['dataset_id']:<14} {arm:<10} {panel_id:<22}"
                        f" x{args.repeats}  metric={METRIC_BY_TASK[dataset['task']]}"
                    )
        return 0

    experiment_id = (
        args.experiment_id or f"ab-{datetime.now(timezone.utc):%Y%m%d}-{uuid.uuid4().hex[:6]}"
    )
    plan_path = RUNS / experiment_id / "plan.md"

    if args.plan:
        path = write_plan(
            experiment_id,
            gt,
            datasets,
            panel_ids,
            arms,
            args.repeats,
            seeds,
            (args.timeout, args.script_timeout, args.score_timeout),
        )
        print(f"Plan frozen: {path.relative_to(BENCH)}")
        # Every selection flag, not just the panel. A suggested command that
        # drops --arm or --repeats silently runs a different experiment under
        # the plan's id; that is how the 795b90 mismatch happened, and
        # enforce_plan now refuses such a command rather than let it repeat.
        print(
            "\nRun it with:\n  python benchmark/run_ab.py"
            f" --experiment-id {experiment_id}"
            + "".join(f" --dataset {d['dataset_id']}" for d in datasets)
            + "".join(f" --arm {a}" for a in arms)
            + "".join(f" --panel-id {p}" for p in panel_ids)
            + f" --repeats {args.repeats}"
            + "".join(f" --seed {s}" for s in seeds[: args.repeats])
        )
        return 0

    if not plan_path.exists():
        print(f"No frozen plan at {plan_path.relative_to(BENCH)}.")
        print("The plan comes before execution. Freeze one with --plan.")
        return 1
    try:
        enforce_plan(
            plan_path,
            datasets=datasets,
            arms=arms,
            panel_ids=panel_ids,
            repeats=args.repeats,
            seeds=seeds,
        )
    except PlanViolation as exc:
        print(f"\nPLAN VIOLATION: {exc}", file=sys.stderr)
        return 1
    print(f"Using frozen plan: {plan_path.relative_to(BENCH)} (cells match)\n")

    split_root = RUNS / experiment_id / "_splits"
    splits: dict[tuple[str, int], dict[str, Any]] = {}
    findings_cache: dict[tuple[str, int], dict[str, Any]] = {}
    total = 0

    for dataset in datasets:
        for rep in range(1, args.repeats + 1):
            seed = seeds[rep - 1]
            key = (dataset["dataset_id"], seed)
            if key not in splits:
                splits[key] = prepare_split(
                    dataset, seed, split_root / f"{dataset['dataset_id']}-seed{seed}"
                )
            split = splits[key]

            # One workspace path per (dataset, seed, repetition), shared by
            # both arms and cleared before each run: the path is part of the
            # prompt, so the arms have to be handed the same one.
            workspace = (
                Path(tempfile.gettempdir()) / f"mlcab-{dataset['openml_id']}-seed{seed}-r{rep}"
            )

            for arm in arms:
                findings = None
                if arm in ADVISE_ARMS:
                    # One `advise` invocation per (dataset, seed), shared by the
                    # two arms that carry it. Sharing the *stdout* is not the
                    # same as sharing an arm's output: `advise` reads the data,
                    # which both arms are given identically, and re-running it
                    # would only risk a difference between the arms that §2
                    # does not allow. What is never shared is a script.
                    if key not in findings_cache:
                        try:
                            findings_cache[key] = mlcompass_findings(
                                split["train_csv"], dataset["target"], args.timeout
                            )
                        except AdviseFailed as exc:
                            print(f"\nAborting after {total} run(s).\n{exc}")
                            return 1
                    findings = findings_cache[key]

                for panel_id in panel_ids:
                    member = PANEL[panel_id]
                    run_id = (
                        f"{experiment_id}-{dataset['openml_id']}-{arm}"
                        f"-{panel_id.replace(':', '-')}-r{rep}"
                    )
                    run_dir = RUNS / run_id
                    outcome = run_cell(
                        dataset=dataset,
                        arm=arm,
                        panel_id=panel_id,
                        member=member,
                        split=split,
                        findings=findings,
                        run_dir=run_dir,
                        workspace=workspace,
                        llm_timeout=args.timeout,
                        script_timeout=args.script_timeout,
                        score_timeout=args.score_timeout,
                        audit_timeout=args.audit_timeout,
                    )
                    if findings is not None:
                        (run_dir / "mlcompass_advise.txt").write_text(
                            findings["advise_stdout"], encoding="utf-8"
                        )

                    defects = outcome["defects"]
                    pre = outcome["defects_pre_revision"]
                    append_result(
                        {
                            "run_id": run_id,
                            "experiment_id": experiment_id,
                            "protocol_version": AB_PROTOCOL_VERSION,
                            "dataset_id": dataset["dataset_id"],
                            "arm": arm,
                            "panel_id": panel_id,
                            "provider": member["provider"],
                            "model": member["model"],
                            "repeat_index": rep,
                            "seed": seed,
                            "started_at_utc": outcome["started"],
                            "mlcompass_commit": _git("rev-parse", "HEAD"),
                            "temperature": outcome["temperature_used"],
                            "temperature_status": outcome["temperature_status"],
                            "status": outcome["status"],
                            "holdout_metric": outcome["holdout_metric"],
                            "holdout_score": outcome["holdout_score"],
                            "defect_count": defects["defect_count"] if defects else "",
                            "defect_count_pre_revision": pre["defect_count"] if pre else "",
                            "defect_count_post_revision": (
                                defects["defect_count"]
                                if (defects and arm in REVISION_ARMS)
                                else ""
                            ),
                            **{
                                d: (int(defects["flags"][d]) if defects else "") for d in DEFECT_IDS
                            },
                            "script_exit_code": outcome["script_exit_code"],
                            "runtime_seconds": round(outcome["runtime"], 3),
                            "input_tokens": outcome["input_tokens"],
                            "output_tokens": outcome["output_tokens"],
                            "artifacts_path": f"runs/{run_id}",
                            "notes": outcome["notes"],
                        }
                    )

                    mark = "ok " if outcome["status"] == "completed" else outcome["status"]
                    score = outcome["holdout_score"]
                    shown = f"{score:.4f}" if isinstance(score, float) else "blank"
                    moved = (
                        f"{pre['defect_count']}->{defects['defect_count']}"
                        if (pre and defects)
                        else (str(defects["defect_count"]) if defects else "n/a")
                    )
                    detail = f"{outcome['holdout_metric'] or 'score'}={shown}, defects={moved}/6"
                    print(f"  {mark:<15} {run_id:<52} {outcome['runtime']:>6.1f}s  {detail}")
                    total += 1

    print(
        f"\n{total} run(s). Results appended to {AB_RESULTS.name};"
        f" evidence under runs/. Holdout splits kept under runs/{experiment_id}/_splits/."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
