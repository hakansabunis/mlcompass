# ab_protocol.md section 2: the control arm gets "the raw CSV path, the target
# column name, the list of packages available in the execution environment, and
# the task: write a training script". The instruction to save the fitted model
# is added because section 3 scores by loading it; it is in *both* prompts, so
# it is part of the task, not part of the intervention. So is the environment
# paragraph, for the sharper reason §9 A5 gives — it is stated to keep the
# arms' failures attributable to the arms.
CONTROL_PROMPT = """\
You are given a tabular dataset saved as a CSV file at this path:

{csv_path}

The target column is: {target}

The columns in the file are:
{columns}

The script will be run by Python {python_version}. These third-party packages \
can be imported in that environment:

{packages}

The Python standard library is there as well. Nothing is installed before the \
script runs, so an import of anything not listed above may fail.

Write a complete Python training script that trains a model to predict the \
target column from the other columns in that file, and saves the fitted model \
to a file in the current working directory so it can be loaded and used to \
predict on new rows later.

Reply with the script inside a single ```python code block, and nothing else.
"""

# The only text that may differ between `control` and `advise`. It is a frame
# around mlcompass's own bytes and carries no advice of its own: if the command
# produced nothing, the block is present and empty, per section 2.
#
# Under 1.0 this block also carried an always-empty `--- mlcompass audit ---`
# section, because audit reads a script and none exists yet. §9 A1 removed it:
# a section headed with a command's name and holding nothing tells the model
# that a check ran and was satisfied, which is advice the harness invented.
ADVISE_BLOCK = """
Below is the verbatim output of mlcompass run on the same inputs.

--- mlcompass advise ---
{advise}
--- end mlcompass advise ---
"""

# The second turn of the `advise+audit` arm, and the only text that may differ
# between `advise` and `advise+audit`. Same discipline as the block above: a
# frame around audit's bytes, and nothing that names a defect, suggests a fix
# or implies there is one to find. "if that output gives you reason to" is
# load-bearing — with an empty findings block, an instruction to revise would
# be the harness telling the model something mlcompass did not.
REVISION_PROMPT = """\
Below is the verbatim output of mlcompass run on the script you just wrote.

--- mlcompass audit ---
{audit}
--- end mlcompass audit ---

Revise the script if that output gives you reason to. Reply with the complete \
final script inside a single ```python code block, and nothing else.
"""


# §9 A8. Deliberately says less than the audit prompt, and the difference is
# the whole point: no findings, no checklist, no hint about what to look for.
# Naming even one concern - leakage, a seed, a metric - would smuggle in the
# content this arm exists to withhold, and the comparison against
# `advise+audit` would measure prompt wording rather than mlcompass output.
#
# The closing instruction is byte-identical to the audit arm's, so the two
# second turns differ only in the presence of the findings block.
SELF_REVISION_PROMPT = """Review the script you just wrote and fix any problems you find in it.

Reply with the complete final script inside a single ```python code block, and nothing else.
"""


def build_self_revision_messages(
    *,
    control_prompt: str,
    first_reply: str,
) -> list[dict[str, str]]:
    """Build the `control+revise` arm's second turn (§9 A8).

    Same three-message shape as `build_revision_messages`, with the control
    prompt as the first turn and no mlcompass content anywhere. The parallel
    is what makes the pair readable: against `advise+audit` this isolates the
    findings, and against `control` it isolates the extra attempt.
    """
    return [
        {"role": "user", "content": control_prompt},
        {"role": "assistant", "content": first_reply},
        {"role": "user", "content": SELF_REVISION_PROMPT},
    ]


# The §9 A17 second turn. The six concerns are the six scored rules, stated as
# a rubric and in the order `check_defects` returns them, so nothing about
# which ones matter is hidden from this arm. What is withheld is the only thing
# `advise+audit` has and this arm does not: a claim about THIS script.
#
# Wording discipline. Each line describes the concern, never its presence. "Is
# every source of randomness seeded" and not "your script is unseeded". A
# reviewer checking whether the rubric leaked a finding should be able to read
# this block against any script at all and find it equally true.
RUBRIC_REVISION_PROMPT = """Review the script you just wrote and fix any problems you find in it.

Check it against these six concerns in particular. This list is generic: it is
the same list for every script, and it says nothing about which of them, if
any, your script actually has.

1. Is every source of randomness seeded, so a re-run reproduces the result?
2. Is anything fitted on data that includes the rows held out for testing?
3. If the input file contains duplicate rows, are they removed before the split?
4. If the target's classes are heavily imbalanced, is the reported metric one
   that survives that imbalance?
5. Is the model evaluated on data it was not trained on?
6. Is the target column excluded from the feature matrix?

Reply with the complete final script inside a single ```python code block, and nothing else.
"""


def build_rubric_revision_messages(
    *,
    control_prompt: str,
    first_reply: str,
) -> list[dict[str, str]]:
    """Build the `control+revise+rubric` arm's second turn (§9 A17).

    Identical to the self-revision arm except for the rubric block. The pair
    exists to answer one question the battery could not previously answer:
    whether `advise+audit`'s fall comes from being told what is wrong with this
    script, or from the scored rubric being named in the prompt at all.
    """
    return [
        {"role": "user", "content": control_prompt},
        {"role": "assistant", "content": first_reply},
        {"role": "user", "content": RUBRIC_REVISION_PROMPT},
    ]


def build_prompts(
    *,
    csv_path: str,
    target: str,
    columns: str,
    advise_stdout: str,
    packages: str | None = None,
) -> tuple[str, str]:
    """Build the `control` and `advise` prompts for one cell.

    The `advise` prompt is the `control` prompt with a block appended, and is
    constructed that way rather than from a parallel template: two templates
    can drift a token apart without anyone noticing, and ab_protocol.md
    section 2 allows exactly one difference. The caller gets both strings and
    `tests/test_ab_prompts.py` asserts the strict-prefix relation holds.

    This is also the `advise+audit` arm's first turn — that arm sends this
    exact string and then a second message, rather than a longer first one.

    `packages` defaults to the environment rather than to a value the caller
    has to remember to pass (§9 A5). It is a parameter at all so that one
    render can be reused across a whole battery and recorded once, not so that
    a caller can supply a list of its own invention.
    """
    control = CONTROL_PROMPT.format(
        csv_path=csv_path,
        target=target,
        columns=columns,
        python_version=platform.python_version(),
        packages=environment_packages() if packages is None else packages,
    )
    block = ADVISE_BLOCK.format(advise=advise_stdout)
    return control, control + block


def build_revision_messages(
    *,
    advise_prompt: str,
    first_reply: str,
    audit_stdout: str,
) -> list[dict[str, str]]:
    """Build the `advise+audit` arm's revision round (§9 A1).

    Three messages, in the order a person would have produced them: the
    `advise` prompt verbatim, the model's own reply to it, and the audit of
    the script that reply contained.

    Two properties this shape buys, both of which §2 needs:

    - The arms stay comparable in the only way a second turn can be. There is
      no prefix relation to assert between a one-turn and a two-turn
      conversation, and pretending otherwise would mean weakening the
      control/advise assertion to something both could satisfy. Instead the
      first turn *is* the `advise` prompt, byte for byte, and that is what the
      test asserts.
    - The arm never sees another arm's work. `first_reply` is this arm's own
      first turn and `audit_stdout` is the audit of that reply's script; the
      caller has no other source to pass.

    An empty `audit_stdout` still produces all three messages. mlcompass
    finding nothing is a finding, and skipping the round would quietly turn
    those cells into `advise` cells reported under the third arm's name.
    """
    return [
        {"role": "user", "content": advise_prompt},
        {"role": "assistant", "content": first_reply},
        {"role": "user", "content": REVISION_PROMPT.format(audit=audit_stdout)},
    ]


def column_listing(frame: Any) -> str:
    """One short line per column: the name and the dtype pandas inferred."""
    return "\n".join(f"  - {name} ({dtype})" for name, dtype in frame.dtypes.items())


