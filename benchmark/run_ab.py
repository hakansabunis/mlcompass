_PROTOCOL_FRACTION = re.compile(r"holdout fraction \*\*([0-9]*\.?[0-9]+)\*\*")
# Both §3 and §5 wrap, so every gap is matched as whitespace rather than as a
# space. A regex that only works while the paragraph happens to fit on one line
# is a check that fails the next time someone reflows the document.
_PROTOCOL_STRATIFY = re.compile(
    r"\*\*stratified\s+on\s+the\s+target\s+for\s+classification", re.IGNORECASE
)
_PROTOCOL_GROUPING = re.compile(r"\*\*split\s+on\s+duplicate\s+groups\*\*", re.IGNORECASE)
_PROTOCOL_TEMPERATURE = re.compile(
    r"temperature\s+([0-9]*\.?[0-9]+)\s+on\s+every\s+arm\s+and\s+every\s+provider", re.IGNORECASE
)
# §2 as amended by §9 A5, in the sentence that defines the control arm: the LLM
# is given "the raw CSV path, the target column name, the list of packages
# available in the execution environment, and the task". That clause is what
# makes the package list the protocol's rather than the harness's, so it is the
# one read back out of the document.
_PROTOCOL_PACKAGE_LIST = re.compile(
    r"the\s+list\s+of\s+packages\s+available\s+in\s+the\s+execution\s+environment", re.IGNORECASE
)


def verify_protocol_constants(
    *,
    text: str | None = None,
    fraction: float | None = None,
    stratify: bool | None = None,
    grouping: bool | None = None,
    temperature: float | None = None,
    packages: bool | None = None,
) -> dict[str, Any]:
    """Check the harness against §3 and §5 of `ab_protocol.md`.

    Called once at the top of a run, before a single cell executes. The point
    is narrow and worth stating: §9 A2, A3 and A4 made the split geometry and
    the temperature *the protocol's* values, and a constant that has been
    retyped into a second file is a constant that will eventually say something
    the protocol does not. If they disagree the run stops, because a battery
    scored under settings the protocol does not describe is evidence for
    nothing.

    Grouping is checked here for a sharper reason than the other two. A wrong
    fraction produces a holdout of visibly the wrong size, and a dropped
    stratification produces a run that fails loudly on a single-class holdout.
    A harness that quietly stopped grouping would keep producing plausible
    scores — inflated for precisely the scripts that leak — and §9 A4 is the
    record of that having happened for seven runs without anyone noticing from
    the numbers alone.

    The package list §9 A5 added is checked the same way and for a version of
    the same reason: a harness that stopped stating the environment would go on
    producing plausible rows, with a share of the failures caused by an absent
    import rather than by the model — and a larger share on the arms that were
    told to handle class imbalance, which is the direction that matters.

    The keyword arguments exist so the check can be exercised against a
    doctored document or a doctored harness without editing either.
    """
    document = AB_PROTOCOL.read_text(encoding="utf-8") if text is None else text
    ours = {
        "holdout_fraction": HOLDOUT_FRACTION if fraction is None else fraction,
        "stratify_classification": STRATIFY_CLASSIFICATION if stratify is None else stratify,
        "group_on_duplicates": GROUP_ON_DUPLICATES if grouping is None else grouping,
        "temperature": TEMPERATURE if temperature is None else temperature,
        "state_package_list": STATE_PACKAGE_LIST if packages is None else packages,
    }

    fraction_match = _PROTOCOL_FRACTION.search(document)
    if fraction_match is None:
        raise ProtocolDrift(
            "ab_protocol.md §3 no longer states a holdout fraction in the form "
            "'holdout fraction **<number>**'. The harness cannot confirm it is "
            "splitting the way the protocol says, so it will not split at all."
        )
    theirs_fraction = float(fraction_match.group(1))
    if theirs_fraction != ours["holdout_fraction"]:
        raise ProtocolDrift(
            f"holdout fraction: ab_protocol.md §3 says {theirs_fraction}, this "
            f"harness uses {ours['holdout_fraction']}. §9 A2 froze the geometry "
            "in the protocol; change it there and here together, or not at all."
        )

    theirs_stratify = bool(_PROTOCOL_STRATIFY.search(document))
    if theirs_stratify != ours["stratify_classification"]:
        raise ProtocolDrift(
            f"stratification: ab_protocol.md §3 says {theirs_stratify}, this "
            f"harness uses {ours['stratify_classification']}. §3 gives the "
            "reason — on an imbalanced target an unstratified draw can leave "
            "the holdout single-class, where ROC AUC is undefined."
        )

    theirs_grouping = bool(_PROTOCOL_GROUPING.search(document))
    if theirs_grouping != ours["group_on_duplicates"]:
        raise ProtocolDrift(
            f"duplicate-group splitting: ab_protocol.md §3 says {theirs_grouping}, "
            f"this harness uses {ours['group_on_duplicates']}. §9 A4 froze it "
            "because without it the holdout shares rows with train, and the "
            "leaking scripts are the ones that score well — the benchmark then "
            "pays for the defect it was built to catch."
        )

    temperature_match = _PROTOCOL_TEMPERATURE.search(document)
    if temperature_match is None:
        raise ProtocolDrift(
            "ab_protocol.md §5 no longer states a frozen temperature in the "
            "form 'temperature <number> on every arm and every provider'. The "
            "harness cannot confirm what it is supposed to send."
        )
    theirs_temperature = float(temperature_match.group(1))
    if theirs_temperature != ours["temperature"]:
        raise ProtocolDrift(
            f"temperature: ab_protocol.md §5 says {theirs_temperature}, this "
            f"harness sends {ours['temperature']}. §9 A3 froze it so that a "
            "difference between lanes cannot come from the setting."
        )

    theirs_packages = bool(_PROTOCOL_PACKAGE_LIST.search(document))
    if theirs_packages != ours["state_package_list"]:
        raise ProtocolDrift(
            f"package list: ab_protocol.md §2 says {theirs_packages}, this harness "
            f"uses {ours['state_package_list']}. §9 A5 froze it because a script "
            "that dies on an absent import has failed for a reason that says "
            "nothing about its quality, and the arms told to handle class "
            "imbalance are the ones most likely to reach for a resampling "
            "library that is not installed."
        )

    return {
        "holdout_fraction": theirs_fraction,
        "stratify_classification": theirs_stratify,
        "group_on_duplicates": theirs_grouping,
        "temperature": theirs_temperature,
        "state_package_list": theirs_packages,
        "source": str(AB_PROTOCOL) if text is None else "<supplied text>",
    }


